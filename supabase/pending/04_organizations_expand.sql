-- 메뉴·재고·수동 매출·POS 메모가 전부 전역 하나였다(리뷰 문서 '서비스화' 섹션).
--
-- 이 단계는 넓히기만 한다:
--   - organizations(사업장)·org_members(사업장별 역할) 테이블을 만들고 지금 사업장을 id=1로 넣는다.
--   - 업무 테이블마다 org_id NOT NULL DEFAULT 1 + FK를 단다. 기본값이 있어 org_id를 모르는 지금 코드의
--     insert가 그대로 동작한다(코드 배포 전에 먼저 걸어도 안전한 이유). PG11+에서 상수 DEFAULT 추가는
--     테이블을 다시 쓰지 않는다.
--   - user_profiles에는 달지 않는다. 사람은 여러 사업장에 속할 수 있어 소속은 org_members가 가진다.
--
-- 아직 하지 않는 것(contract 단계, 코드가 org_id를 쓰게 된 뒤):
--   - DEFAULT 1 제거, 유니크 키에 org_id 포함(daily_sales(sale_date), pos_note id=1 등), RLS 정책,
--     JWT org 클레임, staff_role 'kitchen'/'cashier' CHECK를 사업장별 직무 테이블로.
--
-- 급여 테이블(roster_*, attendance_records, payroll_*)에 컬럼이 붙으므로 적용 전후 유급 분 기준선을
-- 비교한다(payroll_baseline_*.sql, 런북 4단계). 컬럼 추가만이라 금액이 바뀔 경로는 없어야 한다.

-- 업무 테이블 28개에 컬럼을 거는 동안 잠금 대기가 길어지면 결제가 뒤에 줄 선다 — 5초면 포기한다.
set local lock_timeout = '5s';

create table public.organizations (
  id         bigint generated by default as identity primary key,
  name       text not null,
  timezone   text not null default 'Asia/Seoul',
  currency   text not null default 'KRW',
  created_at timestamptz not null default now()
);
alter table public.organizations enable row level security;

insert into public.organizations (id, name) overriding system value values (1, 'Hiyorisando');
select setval(pg_get_serial_sequence('public.organizations', 'id'), 1);

create table public.org_members (
  org_id     bigint not null references public.organizations(id) on delete cascade,
  user_id    uuid   not null references auth.users(id) on delete cascade,
  role       text   not null check (role in ('admin', 'manager', 'staff', 'kiosk')),
  created_at timestamptz not null default now(),
  primary key (org_id, user_id)
);
alter table public.org_members enable row level security;
create index org_members_user_idx on public.org_members (user_id);

-- 지금 계정을 사업장 1의 구성원으로. 역할은 proxy.ts가 쓰는 user_metadata.role과 같은 출처(user_profiles.worker_role).
insert into public.org_members (org_id, user_id, role)
select 1, p.id,
       case p.worker_role when 'admin' then 'admin' when 'manager' then 'manager' when 'kiosk' then 'kiosk' else 'staff' end
from public.user_profiles p
join auth.users u on u.id = p.id;

